/**
 * 슬라이드 타입별 HTML 본문 생성
 * @param {object} s 슬라이드 데이터 객체
 * @param {number} idx 슬라이드 인덱스(0~49)
 * @returns {string} 슬라이드 HTML
 */
function renderSlide(s, idx) {
  const th = THEMES[s.part];
  const pageNum = `${String(idx + 1).padStart(2, '0')} / ${SLIDES.length}`;

  if (s.type === 'cover') {
    return `
    <section class="slide slide-cover" style="--c:${th.color}; --accent:${th.accent};">
      <div class="cover-bg"></div>
      <div class="cover-inner">
        <div class="cover-top">
          <div class="brand-lockup">
            <img src="images/OA_master_LOGO.png" alt="OA MASTER" class="logo-img">
            <span class="brand-name">OA MASTER</span>
          </div>
          <span class="cover-badge">${esc(s.badge)}</span>
        </div>
        <div class="cover-main">
          <h1>${esc(s.title)}</h1>
          <p class="cover-sub">${esc(s.subtitle)}</p>
          <div class="tag-row">
            ${s.tags.map((t) => `<span class="tag-pill"># ${esc(t)}</span>`).join('')}
          </div>
        </div>
        <div class="cover-footer">
          <div class="tool-pills">
            ${s.tools.map((t) => `<span class="tool-pill">${esc(t)}</span>`).join('')}
          </div>
          <span class="page-num cover-page">${pageNum}</span>
        </div>
      </div>
    </section>`;
  }

  if (s.type === 'section') {
    return `
    <section class="slide slide-section" style="--c:${th.color}; --soft:${th.soft}; --accent:${th.accent};">
      <div class="section-stripe"></div>
      <div class="section-inner">
        <div class="section-top">
          <span class="section-day">${esc(s.day)}</span>
          <div class="brand-lockup small">
            <img src="images/OA_master_LOGO.png" alt="OA MASTER" class="logo-img-sm">
            <span>OA MASTER</span>
          </div>
        </div>
        <h1 class="section-title">${esc(s.title).replace(/\n/g, '<br>')}</h1>
        <div class="section-list">
          ${s.items.map((item, i) => `
            <div class="section-item">
              <span class="sec-num">0${i + 1}</span>
              <span>${fmt(item)}</span>
            </div>`).join('')}
        </div>
        <div class="slide-footer light">
          <span>대학생을 위한 AI 활용 오피스 3일 완성</span>
          <span>${pageNum}</span>
        </div>
      </div>
    </section>`;
  }

  if (s.type === 'closing') {
    return `
    <section class="slide slide-closing" style="--c:${th.color}; --accent:${th.accent};">
      <div class="closing-inner">
        <div class="closing-header">
          <span class="cover-badge dark">${esc(s.badge)}</span>
          <h1>${esc(s.title)}</h1>
          <p class="closing-sub">${esc(s.subtitle)}</p>
        </div>
        <div class="grid-3">
          ${s.cards.map((c) => `
            <div class="card-clean">
              <div class="num-badge">${esc(c.num)}</div>
              <h3>${esc(c.title)}</h3>
              <p>${fmt(c.desc)}</p>
            </div>`).join('')}
        </div>
        <div class="closing-footer">
          <div class="brand-lockup">
            <img src="images/OA_master_LOGO.png" alt="OA MASTER" class="logo-img">
            <span class="slogan-text">${esc(s.slogan)}</span>
          </div>
          <span class="page-num">${pageNum}</span>
        </div>
      </div>
    </section>`;
  }

  // 일반 콘텐츠 슬라이드 공통 헤더/푸터
  let bodyHtml = '';

  if (s.type === 'table') {
    bodyHtml = `
      <table class="data-table">
        <thead>
          <tr>${s.headers.map((h) => `<th>${fmt(h)}</th>`).join('')}</tr>
        </thead>
        <tbody>
          ${s.rows.map((r) => `<tr>${r.map((cell) => `<td>${fmt(cell).replace(/\n/g, '<br>')}</td>`).join('')}</tr>`).join('')}
        </tbody>
      </table>`;
  } else if (s.type === 'compare') {
    bodyHtml = `
      <div class="grid-2">
        ${[s.left, s.right].map((col) => `
          <div class="compare-card tone-${col.tone}">
            <div class="compare-badge">${esc(col.badge)}</div>
            <h3>${esc(col.title)}</h3>
            <ul>
              ${col.items.map((it) => `<li>${fmt(it)}</li>`).join('')}
            </ul>
          </div>`).join('')}
      </div>`;
  } else if (s.type === 'cards2') {
    bodyHtml = `
      <div class="grid-2">
        ${s.cards.map((c) => `
          <div class="info-card">
            <div class="info-label">${esc(c.label)}</div>
            <ul>
              ${c.items.map((it) => `<li>${fmt(it)}</li>`).join('')}
            </ul>
          </div>`).join('')}
      </div>`;
  } else if (s.type === 'cards3') {
    bodyHtml = `
      <div class="grid-3">
        ${s.cards.map((c) => `
          <div class="card-clean">
            <div class="num-badge">${esc(c.num)}</div>
            <h3>${esc(c.title)}</h3>
            <p>${fmt(c.desc).replace(/\n/g, '<br>')}</p>
          </div>`).join('')}
      </div>`;
  } else if (s.type === 'splitTableChecklist') {
    bodyHtml = `
      <div class="split-layout">
        <div class="split-left">
          <table class="data-table compact">
            <thead>
              <tr>${s.headers.map((h) => `<th>${fmt(h)}</th>`).join('')}</tr>
            </thead>
            <tbody>
              ${s.rows.map((r) => `<tr>${r.map((cell) => `<td>${fmt(cell).replace(/\n/g, '<br>')}</td>`).join('')}</tr>`).join('')}
            </tbody>
          </table>
        </div>
        <div class="split-right">
          <div class="checklist-panel">
            <h3>${esc(s.checklistTitle)}</h3>
            <ul>
              ${s.checklist.map((item, i) => `<li><span class="chk-box">${i + 1}</span><span>${fmt(item)}</span></li>`).join('')}
            </ul>
          </div>
        </div>
      </div>`;
  } else if (s.type === 'promptCompare') {
    bodyHtml = `
      <div class="grid-2 compact-gap">
        <div class="compare-card tone-bad">
          <div class="compare-badge">피해야 할 방식</div>
          <p class="quote-txt">${fmt(s.bad)}</p>
        </div>
        <div class="compare-card tone-good">
          <div class="compare-badge">권장하는 방식</div>
          <p class="quote-txt">${fmt(s.good)}</p>
        </div>
      </div>
      <div class="prompt-box">
        <div class="prompt-label">실전 복사용 프롬프트</div>
        <p>${fmt(s.prompt)}</p>
      </div>`;
  } else if (s.type === 'promptCards') {
    bodyHtml = `
      <div class="meta-banner">${fmt(s.badge)}</div>
      <div class="prompt-box">
        <div class="prompt-label">실전 복사용 프롬프트</div>
        <p>${fmt(s.prompt)}</p>
      </div>
      <div class="tips-list">
        ${s.tips.map((t) => `<div class="tip-item">${fmt(t)}</div>`).join('')}
      </div>`;
  } else if (s.type === 'stepsCard') {
    bodyHtml = `
      <div class="meta-banner">${fmt(s.badge)}</div>
      <div class="grid-3">
        ${s.steps.map((st) => `
          <div class="card-clean">
            <div class="num-badge">${esc(st.num)}</div>
            <h3>${esc(st.title)}</h3>
            <p>${fmt(st.desc)}</p>
          </div>`).join('')}
      </div>
      ${s.meta && s.meta.length ? `
        <div class="meta-notes">
          ${s.meta.map((m) => `<span>• ${fmt(m)}</span>`).join('')}
        </div>` : ''}`;
  } else if (s.type === 'checklistBox') {
    bodyHtml = `
      <div class="checklist-panel wide">
        <ul>
          ${s.items.map((item, i) => `<li><span class="chk-box">${i + 1}</span><span>${fmt(item)}</span></li>`).join('')}
        </ul>
      </div>
      <div class="callout-box">
        <div class="callout-title">${esc(s.calloutTitle)}</div>
        <p>${fmt(s.calloutText)}</p>
      </div>`;
  }

  return `
  <section class="slide" style="--c:${th.color}; --soft:${th.soft}; --border:${th.border}; --accent:${th.accent};">
    <header class="slide-header">
      <div class="header-meta">
        <span class="part-pill">${esc(th.name)}</span>
        <span class="tag-chip">${esc(s.tag || '')}</span>
      </div>
      <span class="slide-id">${esc(s.id)}</span>
    </header>
    <div class="title-block">
      <h2>${esc(s.title)}</h2>
      ${s.lead ? `<p class="lead">${esc(s.lead)}</p>` : ''}
    </div>
    <main class="slide-body">
      ${bodyHtml}
    </main>
    ${s.summary ? `<div class="summary-bar">${fmt(s.summary)}</div>` : ''}
    <footer class="slide-footer">
      <span class="footer-brand">OA MASTER · AI 활용 오피스 3일 완성</span>
      <span>${pageNum}</span>
    </footer>
  </section>`;
}

