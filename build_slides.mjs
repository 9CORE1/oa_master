// Edge 헤드리스로 PDF 생성 (백그라운드 풀링 프로세스 대기 방지 처리)
const tmpProfile = path.join(ROOT_DIR, '.edge_tmp_pdf');
fs.mkdirSync(tmpProfile, { recursive: true });
if (fs.existsSync(PDF_OUT)) fs.unlinkSync(PDF_OUT);

const fileUrl = 'file:///' + HTML_OUT.replace(/\\/g, '/');
const edgeArgs = [
  '--headless=new',
  '--disable-gpu',
  '--no-sandbox',
  '--no-first-run',
  '--disable-background-networking',
  '--disable-component-update',
  '--disable-extensions',
  '--allow-file-access-from-files',
  '--user-data-dir=' + tmpProfile,
  '--no-pdf-header-footer',
  '--print-to-pdf=' + PDF_OUT,
  fileUrl
];

await new Promise((resolve, reject) => {
  const child = spawn('C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', edgeArgs, {
    stdio: ['ignore', 'pipe', 'pipe']
  });

  let stderrBuf = '';
  let done = false;

  const finish = () => {
    if (done) return;
    done = true;
    setTimeout(() => {
      try { child.kill(); } catch {}
      resolve();
    }, 800);
  };

  child.stderr.on('data', (chunk) => {
    stderrBuf += chunk.toString('utf8');
    if (stderrBuf.includes('bytes written to file')) {
      finish();
    }
  });

  // PDF EOF 완료 여부 폴링 백업
  const poll = setInterval(() => {
    if (fs.existsSync(PDF_OUT)) {
      const sz = fs.statSync(PDF_OUT).size;
      if (sz > 10000) {
        const tail = fs.readFileSync(PDF_OUT).subarray(-32).toString('latin1');
        if (tail.includes('%%EOF')) {
          clearInterval(poll);
          finish();
        }
      }
    }
  }, 500);

  const timer = setTimeout(() => {
    clearInterval(poll);
    if (!done) {
      try { child.kill(); } catch {}
      reject(new Error('Edge PDF 생성 시간 초과\n' + stderrBuf));
    }
  }, 45000);

  child.on('exit', (code) => {
    clearInterval(poll);
    clearTimeout(timer);
    if (!done) {
      done = true;
      if (!fs.existsSync(PDF_OUT)) {
        reject(new Error(`Edge exited (${code}) without creating PDF:\n${stderrBuf}`));
      } else {
        resolve();
      }
    }
  });
});

try {
  const pdfBuf = fs.readFileSync(PDF_OUT);
  const pageMatches = pdfBuf.toString('latin1').match(/\/Type\s*\/Page\b(?!s)/g) || [];
  console.log(`Generated PDF -> ${PDF_OUT} (${pdfBuf.length} bytes, ${pageMatches.length} pages)`);
} finally {
  fs.rmSync(tmpProfile, { recursive: true, force: true });
}
