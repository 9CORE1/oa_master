/**
 * HTML 특수문자 이스케이프
 * @param {string} text 원본 문자열
 * @returns {string} 이스케이프된 문자열
 */
function esc(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * 강조(**굵게**) 및 인라인 코드(`코드`) 마크다운 변환
 * @param {string} text 원본 문장
 * @returns {string} HTML 문자열
 */
function fmt(text) {
  return esc(text)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`(.+?)`/g, '<span class="inline-code">$1</span>');
}

